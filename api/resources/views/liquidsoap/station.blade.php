{{--
    Per-station Liquidsoap script. Rendered by LiquidsoapSupervisor when a
    station is created/updated; written to /var/gocast/liq/{slug}.liq on the
    host; mounted into the station's Liquidsoap container at /station.liq.

    Variables passed in:
      $station         — App\Models\Station
      $icecastPassword — string (from config('services.icecast.source_password'))
      $internalApiKey  — string (matches Laravel's `services.internal_api_key`,
                                 sent in X-Internal-Key header on now-playing pushes)

    IMPORTANT: every string we emit into Liquidsoap source goes through
    json_encode (via @json). Blade's default {{ }} HTML-escapes, which is
    the wrong escaping for a Liquidsoap script — it would turn `&` into
    `&amp;` and corrupt URLs/passwords. json_encode also handles backslashes,
    double quotes, control characters, and unicode the way Liquidsoap's
    lexer expects, so values containing `$ \ "` (e.g. an icecast password
    with shell metacharacters) can't break the script.

    The station slug is the one exception: it's produced by Str::slug() so
    it's already restricted to `[a-z0-9-]` and safe to interpolate raw via
    `{{ }}` after we strip surrounding quotes.
--}}
# === GoCast station: {{ $station->slug }} ===
# Auto-generated by LiquidsoapSupervisor — DO NOT EDIT BY HAND.
# Regenerated on station change; container restart applies it.

settings.log.stdout.set(true)
# Level 2 = warning. Level 3 (info) emits one line per RTSP retry while no
# broadcaster is publishing — that's once per ~2 seconds, all day. Bump back
# up while debugging an audio chain issue.
settings.log.level.set(2)

# Telnet control surface — Laravel sends commands here for skip/reload.
# Bound to 0.0.0.0 inside the container; only reachable on the gocast
# Docker network so Laravel can connect by container name.
settings.server.telnet.set(true)
settings.server.telnet.bind_addr.set("0.0.0.0")
settings.server.telnet.port.set(1234)

# === Inputs ===

# Live broadcaster — pulled from MediaMTX over RTSP. Fallible: only
# present when someone is publishing via WHIP/RTMP/SRT to the station's
# MediaMTX path.
#
# buffer() decouples the RTSP source's own clock from Liquidsoap's main
# clock. Without this, fallback() rejects the source ("This source may
# control its own latency") because input.ffmpeg pulls at its own pace.
# 2s buffer = max 2s of latency from broadcaster to listener; max=10s
# is the overflow threshold before Liquidsoap drops samples.
live = buffer(buffer=2., max=10.,
  input.ffmpeg({!! json_encode("rtsp://host.docker.internal:8554/{$station->slug}/live") !!})
)

# AutoDJ — reads playlist.m3u (written by Laravel's PlaylistFileWriter on
# every track add/edit/reorder/delete). The file is in the same dir that's
# mounted in as /data/playlists/, so relative paths in the m3u resolve
# against /data/playlists/ inside the container.
#
# `mode = "normal"` plays the list top-to-bottom and loops at the end.
#
# `reload_mode = "never"` — auto-reload is disabled. Laravel triggers a
# `playlist_m3u.reload` over telnet after track adds/removes/reorders/edits
# (see PlaylistFileWriter::reload). We deliberately skip "watch" mode
# because every minor metadata edit would otherwise fire a watch event and
# may reset the queue cursor mid-track in some LS 2.x versions.
#
# Fallible when the m3u is missing or empty — fallback() below silently
# promotes the chain to the bed (silence) until tracks exist.
#
# We do NOT wrap this in normalize() — it pumps quiet sections loud and
# crushes louder ones, which sounds like the volume is breathing on its
# own. If we ever need cross-track loudness leveling, swap in a proper
# LUFS limiter rather than the raw normalize() AGC.
autodj = playlist(
  "/data/playlists/playlist.m3u",
  mode = "normal",
  reload_mode = "never"
)

# Standby silence — infallible last resort.
bed = mksafe(blank())

# === Audio brain ===
# Priority: live > autodj > bed. track_sensitive=false means a live
# broadcaster connecting mid-AutoDJ-track interrupts immediately rather
# than waiting for the track to end.
#
# mksafe() promises Liquidsoap's type checker that this chain is infallible.
# Required because output operators downstream refuse fallible sources, and
# fallback() is conservatively typed as fallible even when the last element
# (bed = mksafe(blank())) is provably infallible at runtime.
mixed = mksafe(fallback(track_sensitive=false, [live, autodj, bed]))

# Crossfade on transitions — 2s overlap on track changes and source switches.
# Liquidsoap 2.4 API: `duration` is the only required parameter (the old
# start_next/fade_in/fade_out signature was removed).
# mksafe so the chain stays infallible all the way to the outputs.
output_source = mksafe(crossfade(duration=2., mixed))

# We deliberately do NOT run normalize() here. It's a dynamic AGC that
# pumps quiet audio louder and crushes loud audio quieter — the classic
# "breathing" artifact, especially audible on voice with natural pauses.
# If we ever need cross-track leveling, swap in a tasteful LUFS limiter
# (e.g. the loudness_normalization() snippet from the Liquidsoap docs)
# rather than the raw normalize() operator.

# === Now-playing push ===
#
# Fires every time the metadata at the top of the chain changes — track
# advance in the playlist, broadcaster connecting/disconnecting, etc.
# We POST the payload to Laravel which caches it in Redis; the listener
# API surfaces this so the player UI shows "now playing" without waiting
# for the in-stream ICY frame.
#
# In LS 2.4 on_metadata is a method on the source object (not a top-level
# function). `synchronous=false` runs the callback on a separate task so an
# HTTP hiccup can't block the audio thread.
# X-Internal-Key matches the api container's INTERNAL_API_KEY env var.
def push_now_playing(m) =
  payload = json.stringify(
    {
      slug = {!! json_encode($station->slug) !!},
      title = m["title"],
      artist = m["artist"]
    }
  )
  ignore(http.post(
    "http://api/api/internal/now-playing",
    data=payload,
    headers=[
      ("Content-Type", "application/json"),
      ("Accept", "application/json"),
      ("X-Internal-Key", {!! json_encode($internalApiKey) !!})
    ],
    timeout=5.
  ))
end

output_source.on_metadata(synchronous=false, push_now_playing)

# === Outputs ===

# Icecast — listener URL: https://icecast.gocast.fm{{ $station->icecast_mount }}
output.icecast(
  %mp3(bitrate=128, samplerate=44100),
  host = "icecast",
  port = 8000,
  password = {!! json_encode($icecastPassword) !!},
  mount = {!! json_encode($station->icecast_mount) !!},
  name = {!! json_encode($station->name) !!},
  description = {!! json_encode($station->description ?? '') !!},
  genre = {!! json_encode($station->genre ?? '') !!},
  # Send StreamTitle bytes as UTF-8 — without this, Liquidsoap defaults to
  # ISO-8859-1 and silently rewrites every non-Latin character (Arabic,
  # CJK, accented letters in some forms) to "*" before the metadata even
  # leaves the server.
  encoding = "UTF-8",
  output_source
)

# HLS — listener URL: https://stream.gocast.fm/{{ $station->slug }}/playlist.m3u8
# Caddy serves /var/gocast/hls/{slug}/ (mounted here at /data/hls) from the
# ingest vhost — see the @hls matcher in api/Caddyfile.
#
# The web player streams from Icecast, not from here; HLS exists for clients
# that can't hold a long-lived MP3 socket (iOS lock screen, native apps, CDN
# pull). Single bitrate for v1; add a 64k variant later for cellular ABR.
output.file.hls(
  "/data/hls",
  segment_duration = 2.,
  segments = 5,
  playlist = "playlist.m3u8",
  [("aac", %ffmpeg(format="mpegts", %audio(codec="aac", b="128k")))],
  output_source
)
