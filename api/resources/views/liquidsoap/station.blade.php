# === Per-track loudness ===
#
# A station's library is other people's files: a mastered single sits at
# 0 dBFS, a podcast export twenty decibels below it, and played back to back
# that is a listener reaching for the volume knob between every track. Laravel
# measures each upload once (EBU R128 integrated loudness and true peak) and
# annotates the gain that moves it to the install's target — this operator is
# what makes that annotation mean anything.
#
# `amplify(1., s)` looks like a no-op and is one, until a track arrives
# carrying `liq_amplify`. The 1.0 is the factor for everything else; the
# metadata key overrides it per track, and the name is not ours to choose —
# `settings.amplify.override` is what binds it, and renaming the annotation
# silently stops it applying. Values take a `dB` suffix, without which
# Liquidsoap reads a bare float as a LINEAR multiplier, so "-6" would mean
# inverted phase at six times the volume rather than six decibels down.
#
# ABOVE the crossfade on purpose. cross() decides whether to overlap by
# comparing the db_level of the outgoing and incoming tracks, so it has to see
# the levels a listener will actually hear — leveling afterwards would have it
# reasoning about the raw files and hard cutting pairs that are, once
# corrected, perfectly safe to fade. This is also why an unlevelled library
# made that decision so pessimistic.
#
# Wraps both arms, so jingles are levelled too: a station ID recorded on a
# phone should not be the loudest thing on the station.
#
# This is NOT a compressor and not normalize(). It is one static gain per
# track, chosen before the track starts and unchanged while it plays, so
# nothing here can breathe or pump. LIQUIDSOAP_APPLY_AMPLIFY=false removes the
# operator and the whole library plays at its original levels.
autodj_leveled = amplify(1., autodj_rotation)
@else
# Loudness correction is switched off for this install
# (LIQUIDSOAP_APPLY_AMPLIFY): tracks play at whatever level they were uploaded
# at, and any liq_amplify annotation is inert.
autodj_leveled = autodj_rotation
@endif

# Crossfade AutoDJ track transitions — 2s overlap between consecutive
# playlist tracks. Liquidsoap 2.4+ API: `duration` is the only required
# parameter (the old start_next/fade_in/fade_out signature was removed).
#
# This wraps the AutoDJ rotation alone (rotation + jingles), and deliberately
# NOT the live/AutoDJ fallback below.
# crossfade is a track-boundary operator: it buffers audio and applies a
# fade-out envelope to the outgoing side and a fade-in to the incoming one.
# A live broadcast is one continuous track, so wrapping the fallback meant
# every re-evaluation of it started another 2s gain ramp over live audio.
# Those ramps stacked — "clock.cross: there are currently 551 sources,
# possible source leak" — and listeners heard the level slide down and then
# snap back up. The churn also starved the streaming thread, which then
# logged "Latency is too high: we must catchup 1.22 seconds" and skipped
# samples to recover, adding an audible jump on top of the fades.
#
# Bound to a NEW name rather than rebinding `autodj`: the cross operator
# returns a plain source, which drops the playlist's own methods, and the
# status endpoint must never call methods on it (see the /status handler).
#
# WHY THIS IS GATED, and what to look for if it comes back.
#
# On Liquidsoap 2.4.0 every form of cross() wedged AutoDJ on a track boundary:
# the crossfade() wrapper, a hand-written cross() transition, and the
# cross.smart port below. Output degenerated to a single buffered frame emitted
# forever — a static harmonic spectrum, dead flat for 20s, which listeners hear
# as a stuck-PC buzz. elapsed() climbed past the track length, remaining() froze
# at a constant, decoder End_of_file stopped firing, and NOTHING was logged
# while CPU and memory stayed healthy.
#
# Root cause was upstream, not this script: savonet#4851 attached the
# crossfade's `transition` and `pre_buffer` sources to the passive child clock
# instead of the top-level one, so nothing animated them. Fixed in Liquidsoap
# 2.4.3. The image is pinned to 2.4.5, which also carries savonet#5194 — a
# cross/crossfade crash when source.skip runs from a harbor.http handler, and
# this script serves /status and /healthz over harbor.http.
#
# Detection, since none of it reaches the log: End_of_file should appear once
# per track, and elapsed()+remaining() from /status should equal the track
# duration. If EOF goes quiet while elapsed keeps climbing, it is wedged. Do NOT
# use `request.all` returning two rids as the tell — the playlist legitimately
# prefetches the next track, so two rids is normal on a healthy station.
#
# Recovery is LIQUIDSOAP_CROSSFADE_ENABLED=false plus a relaunch: hard cuts are
# known good, and no code has to change to get there.
@if ($crossfadeEnabled)
# Level-aware transition ported from AzuraCast's `cross.smart`, which is the
# reference implementation for this pipeline. The point is that it does NOT
# always overlap: it compares the loudness of the outgoing and incoming track
# and only fades when the result will not turn to mush, hard cutting otherwise.
# That is what keeps a master limited to 0.0 dBFS — measured on the current
# jazz track — from clipping the encoder while two tracks are summed.
# duration = the cross WINDOW (audio buffered either side of the boundary).
# fade     = the length of the envelopes drawn inside that window, and it must
# be strictly shorter. Book §6.4: "The total duration should always be strictly
# longer than the one of the fades, otherwise the fades will not be complete and
# you will hear abrupt changes in the volume." These were one value for both
# until now, i.e. permanently in exactly that broken case. Laravel clamps the
# fade below the window before rendering.
autodj_cross_duration = {{ number_format($crossfadeDuration, 1, '.', '') }}
autodj_cross_fade = {{ number_format($crossfadeFade, 1, '.', '') }}
autodj_cross_high = {{ number_format($crossfadeHigh, 1, '.', '') }}
autodj_cross_medium = {{ number_format($crossfadeMedium, 1, '.', '') }}
autodj_cross_margin = {{ number_format($crossfadeMargin, 1, '.', '') }}

def autodj_cross_fade_out(s) =
  fade.out(type="sin", duration=autodj_cross_fade, s)
end

def autodj_cross_fade_in(s) =
  fade.in(type="sin", duration=autodj_cross_fade, s)
end

# add() relays metadata from the FIRST available source only, so the incoming
# track is listed first: the other order makes /status announce the track that
# just finished for the whole overlap. normalize=false because add()'s own
# normalization divides by the source count, ducking every transition by 6dB.
def autodj_cross_add(ending, starting) =
  add(normalize=false, [starting, ending])
end

def autodj_cross(a, b) =
  # The fades are built inside each branch, never up front: an unused source
  # still gets created and has to be torn down again.
  #
  # Reading .metadata here also satisfies cross(): it only exposes that field
  # on these records when the script references it, and the type checker needs
  # to see that happen. AzuraCast pokes it with a throwaway `ignore` for
  # exactly this reason — we reference it for real instead.
  if
    # A jingle is never crossfaded. Sliding a produced station ID under the
    # tail of a song is the sound of an accident, and it defeats the point:
    # the ID exists to be heard cleanly. `jingle="true"` is annotated onto
    # every entry in jingles.m3u by PlaylistFileWriter — a station with no
    # jingles never carries it, so this branch is simply never taken there.
    a.metadata["jingle"] == "true" or b.metadata["jingle"] == "true"
  then
    sequence([a.source, b.source])
  elsif
    a.db_level <= autodj_cross_medium
    and b.db_level <= autodj_cross_medium
    and abs(a.db_level - b.db_level) <= autodj_cross_margin
  then
    # Both quiet and close together — safe to fade both ways.
    autodj_cross_add(autodj_cross_fade_out(a.source), autodj_cross_fade_in(b.source))
  elsif
    b.db_level >= a.db_level + autodj_cross_margin
    and a.db_level >= autodj_cross_medium
    and b.db_level <= autodj_cross_high
  then
    # Incoming is much louder — fade the outgoing track out under it.
    autodj_cross_add(autodj_cross_fade_out(a.source), b.source)
  elsif
    a.db_level >= b.db_level + autodj_cross_margin
    and b.db_level >= autodj_cross_medium
    and a.db_level <= autodj_cross_high
  then
    # Outgoing is much louder — fade the incoming track in under it.
    autodj_cross_add(a.source, autodj_cross_fade_in(b.source))
  elsif
    b.db_level >= a.db_level + autodj_cross_margin
    and a.db_level <= autodj_cross_medium
    and b.db_level <= autodj_cross_high
  then
    # Outgoing is already near silence — overlap without fading it further.
    autodj_cross_add(a.source, b.source)
  else
    # Too loud to overlap, or too far apart for one to survive the mix.
    # A hard cut is the honest answer. This is the arm a 0.0 dBFS master
    # takes, which is why the clipping went away.
    sequence([a.source, b.source])
  end
end

autodj_faded = cross(duration=autodj_cross_duration, autodj_cross, autodj_leveled)
@else
# Hard cuts: LIQUIDSOAP_CROSSFADE_ENABLED=false.
autodj_faded = autodj_leveled
@endif

# The limiter is overflow protection, not loudness shaping. Masters
# brick-walled to 0.0 dBFS leave the MP3 encoder no headroom even without an
# overlap. This is NOT normalize() — the gain is static above threshold, so it
# cannot "breathe" on quiet passages.
#
# WHERE IT SITS is the interesting part, and it moved. It used to wrap the
# AutoDJ arm alone, on the rule this file applies everywhere else: keep
# operators off the live path. That left a hole exactly the size of the problem
# it was there to solve — a broadcaster running hot hit the encoder with no
# headroom at all, and the one arm that was protected was the one whose levels
# we control. It now sits at the bottom of the graph instead, past the
# live/AutoDJ fallback, where it catches everything that reaches a listener.
#
# The live-path rule still holds; it just does not apply to this operator. What
# it forbids is TRACK-BOUNDARY operators — cross() re-triggered forever on a
# broadcast that is one endless track and stacked hundreds of gain ramps.
# limit() has no track logic at all: it reads samples and applies static gain
# above a threshold, the same argument that put smooth_add on the live path for
# the watermark. Verified the same way rather than argued: 42 seconds of an
# endless, mark-free carrier through limit() produced no source leak and no
# latency catch-up.
#
# LIQUIDSOAP_LIMITER_INCLUDE_LIVE=false puts it back on the AutoDJ arm, which
# is the previous behaviour exactly — the rollback for an audio-path change,
# same as the crossfade and rotation switches.
@if ($limiterIncludeLive)
autodj_mix = autodj_faded
@else
autodj_mix = limit(threshold={{ number_format($limiterThreshold, 1, '.', '') }}, autodj_faded)
@endif

