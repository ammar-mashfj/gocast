# Live broadcaster — connects straight into this container over the webcast
# WebSocket protocol (the studio) or the Icecast source protocol (BUTT, Mixxx,
# RocketBroadcaster). Fallible: only present while someone is publishing.
#
# Broadcasters publish here directly over the webcast protocol — a WebSocket
# carrying a JSON hello frame then binary MP3. input.harbor speaks it natively
# alongside the traditional Icecast source protocol, so BUTT, Mixxx and friends
# can connect to the same mount with no extra machinery.
#
# This replaced an input.ffmpeg RTSP pull from MediaMTX. WebRTC needed ICE, and
# ICE needs UDP the broadcaster's network may simply refuse: a VPN with leak
# protection, a firewall that blocks UDP, or symmetric NAT all produced a
# session that negotiated successfully and then never carried a byte. A
# WebSocket reaches anyone who can load the studio page.
#
# `auth` is called per connection attempt and validates the short-lived
# broadcast token Laravel minted for the studio (see harbor_auth below).
#
# buffer() decouples harbor's arrival timing from Liquidsoap's main clock so a
# momentary network hiccup on the broadcaster's side doesn't underrun the
# output. 2s nominal, 10s before samples are dropped.
#
# `timeout` is how long a stalled source is kept before harbor declares it gone,
# and it is deliberately below Liquidsoap's default of 30. A broadcaster whose
# connection dies without a clean close — a sleeping laptop, a wifi handover —
# is still holding this mount as far as harbor is concerned, and every attempt
# the studio makes to reconnect is refused until it expires. That window is the
# single thing standing between a dropped broadcast and a recovered one, so it
# is config rather than a literal (LIQUIDSOAP_HARBOR_INPUT_TIMEOUT).
#
# `icy=true` accepts the metadata the broadcaster's own client sends in band —
# the track titles BUTT and Mixxx already push on every song change. Without
# it those frames were parsed and thrown away, so a DJ running a playlist
# showed listeners whatever AutoDJ track happened to be up when they connected,
# forever. The charset is explicit because source clients disagree about it and
# the wrong guess turns every non-Latin title into mojibake; both spellings are
# set since harbor uses one for the Icecast source protocol and one for the
# webcast path.
#
# This is untrusted text on its way to listeners and to our database. Laravel
# is where that is enforced — NowPlayingController caps title and artist at 500
# characters and trims them — not here, because a station container is exactly
# the wrong place to be the last line of defence.
live_in = input.harbor(
  {!! json_encode($station->slug) !!},
  port={{ $harborInputPort }},
  auth=harbor_auth,
  timeout={{ number_format($harborInputTimeout, 1, '.', '') }},
  icy=true,
  icy_metadata_charset={!! json_encode($metadataCharset) !!},
  metadata_charset={!! json_encode($metadataCharset) !!}
)

# on_connect/on_disconnect replace MediaMTX's runOnReady/runOnNotReady hooks:
# they are what tells Laravel to open and close the StreamSession that makes a
# station read as live. Same fast-path caveat as every other event here —
# `stations:reconcile` closes any session a lost notification strands.
#
# Registered as METHODS on the source, not as arguments to input.harbor. The
# argument form still works in 2.4 but logs a deprecation on every boot and is
# slated for removal.
#
# synchronous=false is not optional here: notify() makes an HTTP POST with a
# 5s timeout, and a synchronous callback runs on the streaming thread — a slow
# or hanging API would stall the audio for every listener. Same reasoning as
# the blank.detect callbacks below.
# Local mirror of the same connect/disconnect facts, for /status to report.
#
# WHY THIS EXISTS SEPARATELY FROM `source`. `live` is wrapped in blank.strip
# below, so a broadcaster who mutes their mic is demoted and `current_source()`
# starts saying "autodj" while their socket is still wide open. Anything that
# decides whether to STOP a station must be able to tell "nobody is here" from
# "here but quiet" — stopping the second is yanking a live show off air.
#
# A ref driven by these callbacks rather than only `live_in.is_ready()`: these
# are in-process calls that cannot be lost the way the notify() HTTP posts can,
# and the reader below ORs the two so the answer fails SAFE — any evidence of a
# broadcaster reads as connected.
live_connected = ref(false)

live_in.on_connect(synchronous=false, fun (_) -> begin
  live_connected := true
  notify("live_connected")
end)
live_in.on_disconnect(synchronous=false, fun () -> begin
  live_connected := false
  notify("live_disconnected")
end)

# True when a source client is attached, MUTED OR NOT.
