bed = mksafe(blank())

# === Audio brain ===
# Priority: live > autodj > bed. track_sensitive=false means a live
# broadcaster connecting mid-AutoDJ-track interrupts immediately rather
# than waiting for the track to end.
#
# mksafe() promises Liquidsoap's type checker that this chain is infallible.
# Required because output operators downstream refuse fallible sources, and
# fallback() is conservatively typed as fallible even when the last element
# (bed = mksafe(blank())) is provably infallible at runtime.
mixed = mksafe(fallback(track_sensitive=false, [live, autodj_mix, bed]))

# Nothing further processes the mix: source switches are hard cuts by design.
# Fading between live and AutoDJ would mean fading live audio, which is the
# bug described above. A broadcaster dropping off air should cut to AutoDJ.
#
# `rms()` is what makes /status able to report whether this station is ACTUALLY
# producing sound, as opposed to which arm won the fallback. Those are not the
# same question: a rotation of undecodable files reports `source = "autodj"`
# and emits nothing, and before this there was no way to tell from outside.
#
# Inserted ONCE, here, as a permanent operator in the graph — /status then just
# reads the float it maintains. It must never be applied per request: that is
# exactly the mistake `playlist_length`/`up_next` made (see the /status handler),
# where every poll added a second operator to a crossfaded source.
#
# `duration` is the averaging window, and it is also the UPDATE INTERVAL —
# verified against the image, not assumed: rms() reports 0.0 until the first
# window completes, then refreshes once per window. Keep it short enough that
# any reachable container has a real reading, and let the sweep's multi-minute
# silence timer — not this window — be what absorbs inter-track gaps.
output_source = rms(duration={{ number_format($rmsWindow, 1, '.', '') }}, mixed)

# === Listener-facing metadata ===
#
# From here down the graph splits in two, and the split is the point:
# `output_source` stays the TRUTH — it is what /status reports and what the
# now-playing push reads — while `listener_source` carries what a listener's
# player should display. Those are not always the same sentence.
#
# The case that separates them is the jingle. A station ID is genuinely on air,
# so /status must say so; but swapping every listener's StreamTitle to
# "GoCast FM Jingle" for eight seconds and back is worse than leaving the last
# real track up. The now-playing push already declined to report jingles — this
# closes the other half, which the push could never reach, because
# output.icecast derives its in-stream ICY title from the source's own metadata
# rather than from anything we send Laravel.
#
# `update=false` replaces the metadata wholesale rather than merging, so the
# jingle's own title cannot survive underneath; `strip=true` handles the one
# case with nothing to replay — a jingle before any music has played, which
# `delay(initial=true)` already makes unreachable — by emitting no metadata
# rather than an empty title.
#
# Verified on 2.4.5 with two annotated playlists and a listener on each stream:
# through two jingles, the truth stream reported "Station ID" and the listener
# stream held "Real Song" without a flicker.
def replay_jingle_metadata(s) =
  last_meta = ref(([] : [(string * string)]))

  def rewrite(m) =
    if m["jingle"] == "true" then
      last_meta()
    else
      last_meta := m
      m
    end
  end

  metadata.map(update=false, strip=true, rewrite, s)
end

listener_source = replay_jingle_metadata(output_source)

# === Free-tier watermark ===
#
# A short platform clip mixed OVER the station every few minutes, ducking
# whatever is playing instead of replacing it. Unlike a jingle this is not the
# owner's content and not the owner's decision: it comes from the plan, there
# is no station column for it, and no API surface can switch it off.
#
# WHY IT IS HERE, BELOW THE FALLBACK, AND NOT UP WITH THE JINGLES.
#
# Free plans have autodj_enabled = false, so a free station has no track
# library — its AutoDJ arm is silence and everything a listener hears is a live
# broadcast. Applied to the AutoDJ arm this would therefore be inaudible, and
# applied anywhere above the live/AutoDJ fallback it would be evaded by the one
# action a free station can take: going live. So it sits after the fallback,
# where it catches everything.
#
# That means putting an operator on the live path, which this file otherwise
# treats as forbidden — see the crossfade notes above. The distinction is that
# cross() is a TRACK-BOUNDARY operator, and a live broadcast is one endless
# track: it re-triggered forever and stacked hundreds of sources. smooth_add
# has no track logic at all; it reads a gain getter and sums. Verified rather
# than assumed: 42 seconds of an endless, mark-free carrier with the watermark
# firing repeatedly produced no source leak, no latency catch-up, and a carrier
# level of exactly -25.5 dB against a predicted 0.15 x -9.03 dB.
#
# `output_source` is deliberately left pointing at the un-watermarked mix. The
# /status endpoint and the now-playing push both read it, and they should keep
# reporting what the STATION is playing — a platform ID is not the station's
# now-playing, and routing it through here would also risk the clip's own
# metadata overwriting a real track title. Only the outputs below take the
# watermarked source.
@if ($watermarkSupported)
